def questionnaire_key_for_enterprise(enterprise: str | None) -> str | None:
    value = re.sub(r"[^a-zа-яё]+", " ", str(enterprise or "").casefold())
    if "агро" in value or "agro" in value:
        return "ct_agro"
    if "эсэмбли" in value or "assembly" in value:
        return "ct_assembly"
    # The old 15-question form remains available only for historical records.
    # New assessments require an enterprise-specific questionnaire.
    return None


def get_questionnaire(key: str | None) -> dict:
    return QUESTIONNAIRES.get(str(key or "legacy"), QUESTIONNAIRES["legacy"])


def get_questions(key: str | None) -> list[dict]:
    return [dict(question) for question in get_questionnaire(key)["questions"]]


def get_questionnaire_title(key: str | None) -> str:
    return get_questionnaire(key)["title"]


def score_summary(questions: list[dict], answers: list[int]) -> dict:
    grouped = {"hard": [], "soft": [], "suitability": []}
    for question, answer in zip(questions, answers):
        section = question.get("section", "soft")
        if section in grouped:
            grouped[section].append(int(answer))

    competency_scores = grouped["hard"] + grouped["soft"]
    return {
        "average": round(sum(competency_scores) / len(competency_scores), 2) if competency_scores else 0,
        "hard_average": round(sum(grouped["hard"]) / len(grouped["hard"]), 2) if grouped["hard"] else None,
        "soft_average": round(sum(grouped["soft"]) / len(grouped["soft"]), 2) if grouped["soft"] else None,
        "suitability_score": grouped["suitability"][0] if grouped["suitability"] else None,
    }
